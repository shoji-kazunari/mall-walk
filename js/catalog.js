function hsl(h, s, l) {
  return `hsl(${Math.round(h)}, ${Math.round(s)}%, ${Math.round(l)}%)`;
}

function yen(n) {
  return n.toLocaleString('ja-JP');
}

export function buildCatalog(rng) {
  return SECTIONS.map((sec, si) => {
    const products = [];
    for (let i = 0; i < PRODUCTS_PER_SECTION; i++) {
      const name = [rng.pick(sec.a), rng.pick(sec.b), rng.pick(sec.c)].filter(Boolean).join(' ');
      const hue = rng.range(0, 360);
      const raw = rng.range(sec.price[0], sec.price[1]);
      const price = Math.max(sec.price[0], Math.round(raw / 100) * 100 - 20);
      products.push({
        section: si,
        index: i,
        name,
        maker: rng.pick(MAKERS),
        price,
        priceLabel: `¥${yen(price)}`,
        age: rng.pick(si === 6 ? [0, 0, 1] : [3, 3, 4, 5, 6, 8]),
        desc: [rng.pick(sec.desc), rng.pick(COMMON_DESC)].filter(Boolean).join(''),
        size: {
          w: rng.range(...sec.size.w),
          h: rng.range(...sec.size.h),
          d: rng.range(...sec.size.d),
        },
        art: {
          bg: hsl(hue, rng.range(55, 85), rng.range(48, 62)),
          band: hsl(hue + rng.range(140, 220), rng.range(55, 80), rng.range(35, 48)),
          window: hsl(hue, 40, 94),
          ink: hsl(hue + rng.range(-40, 40), rng.range(60, 90), rng.range(35, 55)),
          ink2: hsl(rng.range(0, 360), rng.range(60, 90), rng.range(50, 65)),
          tilt: rng.range(-0.15, 0.15),
        },
      });
    }
    return products;
  });
}
